export function getEnemyStats(typeKey, floorNumber = 1) {
  const normKey = (typeKey || '').toUpperCase();
  const base = ENEMY_TYPES[normKey] || ENEMY_TYPES[typeKey] || ENEMY_TYPES.GRUNT;
  const floorMultiplier = 1 + Math.max(0, floorNumber - 1) * 0.1;

  return {
    ...base,
    maxHp: Math.round(base.hp * floorMultiplier),
    hp: Math.round(base.hp * floorMultiplier),
    damage: Math.round(base.damage * floorMultiplier),
    speed: base.speed,
  };
}
